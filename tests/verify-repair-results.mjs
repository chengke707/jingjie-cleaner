import assert from 'node:assert/strict';
import { classifyRepairStep as classify, summarizeRepair, decodeRepairLog } from '../repair-results.mjs';
const step = (id, exitCode = 0, status = 'succeeded') => ({ id, exitCode, status });
const chinese = 'Windows 资源保护未找到任何完整性违规。';
assert.equal(classify(step('sfc'), chinese).status, 'succeeded');
assert.equal(classify(step('sfc-verify'), chinese).status, 'succeeded');
assert.equal(decodeRepairLog(Buffer.concat([Buffer.from([255,254]), Buffer.from(chinese,'utf16le')])), chinese);
assert.equal(decodeRepairLog(Buffer.from('\uFEFF' + chinese)), chinese);
assert.equal(classify({ id:'dism', status:'interrupted' }, 'Error: 112\nThere is not enough space on the disk.').nextAction.type, 'cleanup');
assert.equal(classify(step('dism', -2146498283), 'Error: 0x800f0915 The repair content could not be found anywhere.').nextAction.type, 'update');
assert.equal(classify(step('dism',3010), 'Operation completed.').status, 'review');
assert.equal(classify(step('sfc'), 'Windows Resource Protection found corrupt files but was unable to fix some of them.').status, 'failed');
assert.equal(classify(step('sfc-verify'), 'Windows Resource Protection found integrity violations.').status, 'failed');
assert.equal(classify(step('dism-verify'), 'The component store is repairable.').status, 'failed');
assert.equal(classify(step('dism'), 'The operation completed successfully.').status, 'review');
assert.equal(classify(step('sfc'), 'Verification 68% complete').status, 'review');
const job = { status:'completed', steps:['dism','dism-verify','sfc','sfc-verify'].map(id => step(id)) };
const texts = { dism:'The restore operation completed successfully.', 'dism-verify':'No component store corruption detected.', sfc:chinese, 'sfc-verify':chinese };
assert.equal(summarizeRepair(job,texts).verified, true);
assert.equal(summarizeRepair(job,texts).status, 'completed');
assert.equal(summarizeRepair(job,{...texts, 'sfc-verify':'incomplete output'}).verified, false);
assert.equal(summarizeRepair(job,{...texts, 'sfc-verify':'incomplete output'}).status, 'review');
assert.equal(summarizeRepair({...job,steps:[step('dism'),step('sfc')]},texts).verified, false);
assert.equal(summarizeRepair({...job,steps:[step('dism'),step('sfc')]},texts).status, 'review');
assert.equal(summarizeRepair({status:'cancelled',steps:[{id:'dns',status:'skipped'}]}).status, 'cancelled');
assert.equal(summarizeRepair({status:'failed',steps:[{id:'dns',status:'interrupted'}]}).status, 'failed');
console.log('PASS Chinese/English results, legacy errors, encodings, post-repair verification, partial outputs never claim success');
