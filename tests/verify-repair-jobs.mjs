import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRepairJobs } from '../repair-jobs.mjs';
const fixture = await fs.mkdtemp(path.join(process.cwd(), 'work', 'repair-fixture-'));
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
let calls = [], finish;
const launch = input => { calls.push(input); return { pid: process.pid, completion: new Promise(resolve => { finish = resolve; }) }; };
const options = { dataDir: fixture, appDir: process.cwd(), launch, freeSpace: async () => 20 * 1024 ** 3 };
const jobs = createRepairJobs(options);
assert.equal(await jobs.get(), null);
for (const value of [[], ['open-update'], ['flush-dns','flush-dns'], ['__proto__'], null, ['repair-components','arbitrary-command']]) await assert.rejects(jobs.start(value));
assert.equal(calls.length, 0);
console.log('PASS empty, duplicate, arbitrary and helper operations never launch a repair');
const started = await jobs.start(['flush-dns', 'repair-components']);
assert.deepEqual(started.steps.map(step => step.id), ['dns','dism','dism-verify','sfc','sfc-verify']);
assert.equal(started.status, 'starting');
await assert.rejects(jobs.start(['flush-dns']));
assert.equal(calls.length, 1);
assert.equal((await createRepairJobs(options).get()).status, 'starting');
finish(1223);
for (let i=0;i<50 && (await jobs.get()).status === 'starting';i++) await pause(20);
assert.equal((await jobs.get()).status, 'cancelled');
assert.ok((await jobs.get()).steps.every(step => step.status === 'skipped'));
console.log('PASS one batch launch, duplicate prevention, persistence and cancelled UAC result');
await pause(30);
const next = await jobs.start(['repair-components']);
const worker = { status: 'review', message: '需要查看 SFC 输出', steps: [{id:'dism',status:'succeeded'},{id:'sfc',status:'review'}] };
await fs.writeFile(path.join(calls[1].directory, 'progress.json'), JSON.stringify(worker));
await fs.writeFile(path.join(calls[1].directory, 'sfc.log'), 'fixture output: repaired some files');
finish(0); await pause(50);
assert.equal((await jobs.get()).status, 'review');
assert.equal((await createRepairJobs(options).get()).status, 'review');
assert.match((await jobs.log(next.id, 'sfc')).text, /fixture output/);
await assert.rejects(jobs.log('../../outside', 'sfc'));
await assert.rejects(jobs.log(next.id, '../latest.json'));
console.log('PASS real worker status preserved, readable persisted logs, traversal refused');
await jobs.start(['flush-dns']); finish(1); await pause(60);
assert.equal((await jobs.get()).status, 'failed');
console.log('PASS exit without worker result is failure, never success');
await jobs.start(['flush-dns']);
const restarted = createRepairJobs({ ...options, alive: () => false });
assert.equal((await restarted.get()).status, 'review');
finish(1); await pause(50);
console.log('PASS terminated process after restart reports unconfirmed result');
const broken = createRepairJobs({ dataDir: path.join(fixture, 'broken'), appDir: fixture, launch: () => { throw new Error('synthetic spawn failure'); } });
await broken.start(['flush-dns']); await pause(60);
assert.equal((await broken.get()).status, 'failed');
console.log('PASS launch error is persisted; no real repair commands were executed');
const lowDisk = createRepairJobs({ ...options, dataDir: path.join(fixture, 'low-disk'), freeSpace: async () => 1024 ** 3 });
const before = calls.length;
const blocked = await lowDisk.start(['flush-dns','repair-components']);
assert.equal(blocked.status, 'blocked'); assert.equal(calls.length, before);
assert.match(blocked.message, /1.0 GB/); assert.ok(blocked.steps.every(step => step.status === 'skipped'));
assert.equal((await lowDisk.get()).status, 'blocked');
assert.equal((await lowDisk.history())[0].steps.find(step => step.id === 'dism').nextAction.type, 'cleanup');
const records = await jobs.history();
assert.ok(records.length >= 4); assert.ok(records.some(job => job.id === next.id));
assert.equal((await jobs.get(next.id)).status, 'review');
await assert.rejects(jobs.get('../../outside'));
console.log('PASS disk preflight never elevates or partially executes a blocked batch; history survives restarts');
const rename = fs.rename;
let failPersistence = false, finishPersistence;
const persistenceJobs = createRepairJobs({ ...options, dataDir:path.join(fixture,'persistence'), launch:() => { failPersistence=true; return {pid:process.pid,completion:new Promise(resolve=>{finishPersistence=resolve;})}; } });
fs.rename = async (from,to) => { if (failPersistence && to.endsWith('latest.json')) { failPersistence=false; throw Object.assign(new Error('Synthetic disk full'),{code:'ENOSPC'}); } return rename(from,to); };
try { await assert.rejects(persistenceJobs.start(['flush-dns']), /勿重复启动/); }
finally { fs.rename=rename; }
await assert.rejects(persistenceJobs.start(['flush-dns']), /已有修复/);
finishPersistence(1); await pause(80);
assert.equal((await persistenceJobs.get()).status,'failed');
await persistenceJobs.start(['flush-dns']); finishPersistence(1223); await pause(60);
assert.equal((await persistenceJobs.get()).status,'cancelled');
console.log('PASS disk-full persistence after launch still tracks completion and releases busy state');
